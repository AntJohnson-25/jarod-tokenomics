"""Export the seed pricing catalog + pricing history from the desktop Jarod DB
into src/data.js. Reads ONLY pricing tables (never usage data or config.json)."""
import json
import os
import sqlite3
import sys

DB = os.path.join(os.environ["LOCALAPPDATA"], "CTSG", "Tokenomics", "tokenomics.db")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "data.js")

c = sqlite3.connect("file:" + DB.replace("\\", "/") + "?mode=ro", uri=True)
latest = c.execute("select max(snapshot_date) from pricing_history").fetchone()[0]

pricing = [
    {"provider": p, "model": m, "input": i, "output": o, "cached": ca, "context": ctx, "tier": t}
    for p, m, i, o, ca, ctx, t in c.execute(
        "select provider,model,input_cost,output_cost,cached_cost,context_window,tier "
        "from pricing_history where snapshot_date=? order by provider,model",
        (latest,),
    )
]
history = [
    {"snapshot_date": d, "provider": p, "model": m, "input_cost": i, "output_cost": o,
     "cached_cost": ca, "context_window": ctx, "tier": t}
    for d, p, m, i, o, ca, ctx, t in c.execute(
        "select snapshot_date,provider,model,input_cost,output_cost,cached_cost,context_window,tier "
        "from pricing_history order by snapshot_date,provider,model"
    )
]
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/gen_data.py - seed catalog (list prices, USD per 1M tokens)\n")
    f.write("window.JAROD_SEED=" + json.dumps(
        {"seedDate": latest, "pricing": pricing, "history": history},
        separators=(",", ":"), ensure_ascii=False) + ";\n")
print("models", len(pricing), "history rows", len(history), "latest", latest)
